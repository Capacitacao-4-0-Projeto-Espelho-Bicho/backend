-- PostgreSQL 14+ | Instalação nova, isolada dos modelos anteriores.
-- Não migra dados existentes. Não contém DROP TABLE.
-- Execute o arquivo inteiro; qualquer erro reverte a instalação.
-- Estrutura, cadastros de referência e um trigger para guardar o perfil anterior.
-- As demais regras ficam na aplicação.
BEGIN;
CREATE SCHEMA capacitacao;
SET LOCAL search_path TO capacitacao, public;
-- Aqui fica o cadastro de cada pessoa: nome, email e os dados que a API usa no login.
-- A senha fica como hash, nunca como texto puro. Quem faz o login é a API.
CREATE TABLE usuario (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    data_cadastro  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

-- É a lista de competências que vamos mostrar para o usuário escolher.
-- Por exemplo: liderança, criatividade e resolução de problemas.
CREATE TABLE competencia (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    descricao   TEXT,
    data_criado TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_competencia_nome UNIQUE (nome)
);

-- Guarda os quatro níveis: Iniciante, Básico, Intermediário e Avançado.
-- As faixas de pontuação ficam aqui como referência para o código calcular o resultado.
CREATE TABLE nivel (
    id               INT PRIMARY KEY,
    nome             VARCHAR(50) NOT NULL,
    descricao        TEXT,
    ordem            INT NOT NULL UNIQUE,
    pontuacao_minima DECIMAL(5,2) NOT NULL,
    pontuacao_maxima DECIMAL(5,2) NOT NULL,
    CONSTRAINT chk_nivel_ordem CHECK (ordem BETWEEN 1 AND 4),
    CONSTRAINT chk_pontuacao CHECK (pontuacao_minima >= 0 AND pontuacao_maxima <= 100)
);

-- Divide cada competência em partes mais específicas que a pessoa pode desenvolver.
-- Cada habilidade pertence a uma competência e pode ter tarefas em diferentes níveis.
CREATE TABLE habilidade (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia_id INT          NOT NULL,
    nome           VARCHAR(200) NOT NULL,
    descricao      TEXT,
    ordem          INT          NOT NULL,
    data_criado    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_habilidade_competencia FOREIGN KEY (competencia_id) REFERENCES competencia(id) ON DELETE CASCADE,
    CONSTRAINT uq_habilidade_competencia_ordem UNIQUE (competencia_id, ordem)
);

-- Apesar do nome, esta tabela guarda as QUESTÕES DO NIVELAMENTO.
-- Cada questão está ligada a uma habilidade e a um nível.
-- As tarefas oferecidas depois do resultado ficam em atividade, com questões em atividade_questao.
CREATE TABLE tarefa (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habilidade_id      INT          NOT NULL,
    nivel_id           INT          NOT NULL,
    enunciado          TEXT         NOT NULL,
    instrucoes         TEXT,
    ordem              INT          NOT NULL,
    tempo_estimado_min INT          DEFAULT 15,
    data_criado        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tarefa_habilidade FOREIGN KEY (habilidade_id) REFERENCES habilidade(id) ON DELETE CASCADE,
    CONSTRAINT fk_tarefa_nivel FOREIGN KEY (nivel_id) REFERENCES nivel(id) ON DELETE RESTRICT,
    CONSTRAINT chk_tarefa_ordem CHECK (ordem > 0)
);

-- São as opções de resposta de cada questão de nivelamento.
-- Cada opção tem sua própria pontuação, por exemplo: 0, 1, 2 ou 3 pontos.
-- Não existe marcação de certo ou errado. O valor depende do comportamento descrito, não da posição da opção.
CREATE TABLE alternativa (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id      INT          NOT NULL,
    texto          TEXT         NOT NULL,
    ordem          INT          NOT NULL,
    pontuacao      NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (pontuacao >= 0),
    justificativa  TEXT,
    data_criado    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alternativa_tarefa FOREIGN KEY (tarefa_id) REFERENCES tarefa(id) ON DELETE CASCADE,
    CONSTRAINT chk_alternativa_quantidade CHECK (ordem BETWEEN 1 AND 5),
    CONSTRAINT uq_alternativa_tarefa_ordem UNIQUE (tarefa_id, ordem)
);


-- Guarda quais competências o usuário escolheu desenvolver.
-- Se ele escolher três competências, terá três registros aqui, um para cada escolha.
CREATE TABLE usuario_competencia (
 usuario_id INT REFERENCES usuario(id) ON DELETE CASCADE,
 competencia_id INT REFERENCES competencia(id),
 selecionada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ativa BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY(usuario_id, competencia_id)
);

-- Guarda o contexto atual da pessoa: tempo disponível, ambiente, recursos
-- e com quem ela pode fazer as atividades. Isso pode ajudar a escolher tarefas que caibam na rotina.
CREATE TABLE perfil_usuario (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
 ambiente VARCHAR(30) NOT NULL, tempo VARCHAR(30) NOT NULL,
 recursos VARCHAR(30) NOT NULL, interlocutores VARCHAR(30) NOT NULL,
 origem_atualizacao VARCHAR(30) NOT NULL DEFAULT 'onboarding',
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Guarda os perfis anteriores para não perder o histórico quando algo mudar.
-- Por exemplo: antes a pessoa tinha pouco tempo, agora tem mais disponibilidade.
-- O trigger copia o perfil antigo para cá quando ambiente, tempo, recursos ou interlocutores mudam.
CREATE TABLE historico_perfil (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
 ambiente VARCHAR(30) NOT NULL, tempo VARCHAR(30) NOT NULL,
 recursos VARCHAR(30) NOT NULL, interlocutores VARCHAR(30) NOT NULL,
 origem VARCHAR(30) NOT NULL, motivo TEXT,
 data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- É o cadastro de formulários gerais, como as perguntas para conhecer o perfil da pessoa.
-- O nivelamento das competências usa avaliacao_usuario e as questões da tabela tarefa.
CREATE TABLE questionario (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL, descricao TEXT, ativo BOOLEAN NOT NULL DEFAULT TRUE,
 data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Guarda as perguntas dos formulários gerais e a ordem em que aparecem.
-- Também indica se a resposta é obrigatória e se a pergunta tem relação com algum campo do perfil.
CREATE TABLE pergunta (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 questionario_id INT NOT NULL REFERENCES questionario(id), titulo VARCHAR(255) NOT NULL,
 descricao TEXT, tipo VARCHAR(30) NOT NULL DEFAULT 'unica'
 CHECK(tipo IN ('unica','multipla','texto','numero')),
 ordem INT NOT NULL, obrigatoria BOOLEAN NOT NULL DEFAULT TRUE, campo_perfil VARCHAR(30),
 UNIQUE(questionario_id,ordem), UNIQUE(id,questionario_id)
);

-- Guarda as opções de resposta das perguntas dos formulários gerais.
-- Por exemplo: pouco tempo, tempo moderado ou bastante tempo disponível.
CREATE TABLE opcao_pergunta (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pergunta_id INT NOT NULL REFERENCES pergunta(id), codigo VARCHAR(50) NOT NULL,
 texto VARCHAR(255) NOT NULL, valor VARCHAR(100), ordem INT NOT NULL,
 ativa BOOLEAN NOT NULL DEFAULT TRUE, UNIQUE(pergunta_id,codigo), UNIQUE(id,pergunta_id)
);

-- Registra cada vez que uma pessoa começa a preencher um formulário geral.
-- Permite saber quem está respondendo, qual formulário é e se já terminou.
CREATE TABLE avaliacao_questionario (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INT NOT NULL REFERENCES usuario(id), questionario_id INT NOT NULL REFERENCES questionario(id),
 tipo VARCHAR(30) NOT NULL DEFAULT 'perfil',
 status VARCHAR(20) NOT NULL DEFAULT 'em_andamento' CHECK(status IN ('em_andamento','concluida','cancelada')),
 data_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, data_conclusao TIMESTAMP,
 UNIQUE(id,questionario_id)
);

-- Guarda o que a pessoa respondeu no formulário geral.
-- A resposta pode ser uma opção escolhida, um texto ou um número.
CREATE TABLE resposta_questionario (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 avaliacao_id INT NOT NULL, questionario_id INT NOT NULL, pergunta_id INT NOT NULL,
 opcao_id INT, resposta_texto TEXT, resposta_numero DECIMAL,
 data_resposta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(avaliacao_id,questionario_id) REFERENCES avaliacao_questionario(id,questionario_id),
 FOREIGN KEY(pergunta_id,questionario_id) REFERENCES pergunta(id,questionario_id),
 FOREIGN KEY(opcao_id,pergunta_id) REFERENCES opcao_pergunta(id,pergunta_id),
 CHECK(num_nonnulls(opcao_id,resposta_texto,resposta_numero)=1)
);

-- Registra uma tentativa de nivelamento de UMA competência para UM usuário.
-- Guarda os pontos obtidos, o máximo possível, o percentual e o nível daquela tentativa.
-- Uma nova tentativa gera outro registro, sem apagar o resultado anterior.
CREATE TABLE avaliacao_usuario (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INT NOT NULL, competencia_id INT NOT NULL,
 tipo VARCHAR(30) NOT NULL DEFAULT 'nivelamento' CHECK(tipo IN ('nivelamento','reavaliacao')),
 status VARCHAR(20) NOT NULL DEFAULT 'em_andamento' CHECK(status IN ('em_andamento','concluida','cancelada')),
 data_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, data_conclusao TIMESTAMP,
 pontuacao_total NUMERIC(12,2) CHECK(pontuacao_total>=0),
 pontuacao_maxima NUMERIC(12,2) CHECK(pontuacao_maxima>0),
 percentual_pontuacao NUMERIC(5,2) CHECK(percentual_pontuacao BETWEEN 0 AND 100),
 nivel_id INT REFERENCES nivel(id),
 FOREIGN KEY(usuario_id,competencia_id) REFERENCES usuario_competencia(usuario_id,competencia_id),
 UNIQUE(id,usuario_id,competencia_id),
 CHECK(pontuacao_total<=pontuacao_maxima)
);

CREATE UNIQUE INDEX uq_avaliacao_aberta ON avaliacao_usuario(usuario_id,competencia_id)
 WHERE status='em_andamento';

-- Guarda quais questões entraram naquela tentativa de nivelamento.
-- Também guarda o máximo de pontos de cada questão naquela tentativa.
-- Assim, a API pode preservar o cálculo mesmo se a pontuação do cadastro mudar depois.
CREATE TABLE avaliacao_tarefa (
 avaliacao_id INT NOT NULL REFERENCES avaliacao_usuario(id),
 tarefa_id INT NOT NULL REFERENCES tarefa(id),
 pontuacao_maxima NUMERIC(7,2) NOT NULL CHECK(pontuacao_maxima>=0),
 PRIMARY KEY(avaliacao_id,tarefa_id)
);

ALTER TABLE alternativa ADD CONSTRAINT uq_alternativa_id_tarefa UNIQUE(id,tarefa_id);

-- Guarda a alternativa que o usuário marcou e quantos pontos recebeu naquela resposta.
-- A API copia a pontuação da alternativa para pontuacao_obtida, preservando o valor da época.
-- Também pode guardar quanto tempo a pessoa levou para responder.
CREATE TABLE resposta_tarefa (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 avaliacao_id INT NOT NULL, tarefa_id INT NOT NULL, alternativa_id INT NOT NULL,
 pontuacao_obtida NUMERIC(7,2) NOT NULL CHECK(pontuacao_obtida>=0),
 tempo_gasto_seg INT CHECK(tempo_gasto_seg>=0),
 data_resposta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(avaliacao_id,tarefa_id),
 FOREIGN KEY(avaliacao_id,tarefa_id) REFERENCES avaliacao_tarefa(avaliacao_id,tarefa_id),
 FOREIGN KEY(alternativa_id,tarefa_id) REFERENCES alternativa(id,tarefa_id)
);

-- Guarda o resultado atual da pessoa em cada competência: nível, pontos e percentual.
-- Por exemplo: 18 de 24 pontos possíveis equivalem a 75%.
-- A API calcula e atualiza esses valores; a avaliação de origem continua no histórico.
CREATE TABLE progresso_usuario (
 usuario_id INT NOT NULL, competencia_id INT NOT NULL,
 avaliacao_id INT NOT NULL UNIQUE, nivel_atual INT NOT NULL REFERENCES nivel(id),
 pontuacao_total NUMERIC(12,2) NOT NULL CHECK(pontuacao_total>=0),
 pontuacao_maxima NUMERIC(12,2) NOT NULL CHECK(pontuacao_maxima>0),
 total_tarefas INT NOT NULL CHECK(total_tarefas>0),
 percentual_pontuacao NUMERIC(5,2) NOT NULL CHECK(percentual_pontuacao BETWEEN 0 AND 100),
 data_ultima_avaliacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(usuario_id,competencia_id),
 CHECK(pontuacao_total<=pontuacao_maxima),
 FOREIGN KEY(avaliacao_id,usuario_id,competencia_id)
 REFERENCES avaliacao_usuario(id,usuario_id,competencia_id)
);

-- Aqui ficam as tarefas oferecidas depois do nivelamento, por habilidade e nível.
-- Por enquanto, cada tarefa é um conjunto de questões de múltipla escolha.
-- A entrega será o conjunto de respostas, sem envio de arquivos ou relatos como evidência.
CREATE TABLE atividade (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(200) NOT NULL, competencia_id INT NOT NULL REFERENCES competencia(id),
 habilidade_id INT NOT NULL REFERENCES habilidade(id), dificuldade INT NOT NULL REFERENCES nivel(id),
 duracao_min INT NOT NULL CHECK(duracao_min>0),
 ambiente VARCHAR(30) NOT NULL DEFAULT 'qualquer', tempo VARCHAR(30) NOT NULL DEFAULT 'qualquer',
 recursos VARCHAR(30) NOT NULL DEFAULT 'qualquer', interlocutores VARCHAR(30) NOT NULL DEFAULT 'qualquer',
 descricao TEXT,
 data_criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Registra qual tarefa foi oferecida a qual pessoa e com base em qual avaliação.
-- Também permite acompanhar se ela aceitou, recusou, começou ou concluiu a tarefa.
-- A escolha da tarefa e a mudança de status são feitas pelo código da aplicação.
CREATE TABLE recomendacao (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INT NOT NULL REFERENCES usuario(id), atividade_id INT NOT NULL REFERENCES atividade(id),
 avaliacao_id INT NOT NULL REFERENCES avaliacao_usuario(id),
 data_gerada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, regra_usada VARCHAR(100) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'gerada'
 CHECK(status IN ('gerada','aceita','recusada','em_andamento','concluida','cancelada')),
 motivo_recusa TEXT, data_decisao TIMESTAMP,
 UNIQUE(usuario_id,atividade_id,avaliacao_id)
);

-- Registra quando o usuário começou e terminou uma tarefa recomendada.
-- A entrega está nas respostas ligadas a esta execução, não em um arquivo enviado.
-- A API calcula os pontos e controla a conclusão; o nível não muda automaticamente.
CREATE TABLE execucao (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recomendacao_id INT NOT NULL UNIQUE REFERENCES recomendacao(id),
 atividade_id INT NOT NULL REFERENCES atividade(id),
 status VARCHAR(20) NOT NULL DEFAULT 'em_andamento'
 CHECK(status IN ('em_andamento','concluida','cancelada')),
 data_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, data_conclusao TIMESTAMP,
 pontuacao_total NUMERIC(12,2) CHECK(pontuacao_total>=0),
 pontuacao_maxima NUMERIC(12,2) CHECK(pontuacao_maxima>0),
 percentual_pontuacao NUMERIC(5,2) CHECK(percentual_pontuacao BETWEEN 0 AND 100),
 CHECK(pontuacao_total<=pontuacao_maxima),
 UNIQUE(id,atividade_id)
);

-- São as questões de múltipla escolha que fazem parte de uma tarefa após o nivelamento.
-- Uma tarefa pode ter várias questões, apresentadas na ordem cadastrada.
CREATE TABLE atividade_questao (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atividade_id INT NOT NULL REFERENCES atividade(id),
 enunciado TEXT NOT NULL, instrucoes TEXT,
 ordem INT NOT NULL CHECK(ordem>0),
 UNIQUE(atividade_id,ordem), UNIQUE(id,atividade_id)
);

-- São as opções de resposta de cada questão da tarefa.
-- Cada opção pode ter sua própria pontuação, como nas questões do nivelamento.
CREATE TABLE atividade_alternativa (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 questao_id INT NOT NULL REFERENCES atividade_questao(id),
 texto TEXT NOT NULL, ordem INT NOT NULL CHECK(ordem>0),
 pontuacao NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK(pontuacao>=0),
 justificativa TEXT,
 UNIQUE(questao_id,ordem), UNIQUE(id,questao_id)
);

-- Guarda quais questões fazem parte da tarefa que o usuário começou.
-- A API registra a lista e o máximo de pontos de cada questão para preservar aquela execução.
CREATE TABLE execucao_questao (
 execucao_id INT NOT NULL,
 atividade_id INT NOT NULL,
 questao_id INT NOT NULL,
 pontuacao_maxima NUMERIC(7,2) NOT NULL CHECK(pontuacao_maxima>=0),
 PRIMARY KEY(execucao_id,questao_id),
 FOREIGN KEY(execucao_id,atividade_id) REFERENCES execucao(id,atividade_id),
 FOREIGN KEY(questao_id,atividade_id) REFERENCES atividade_questao(id,atividade_id)
);

-- Aqui fica a entrega do usuário: a alternativa marcada em cada questão da tarefa.
-- Cada questão tem uma resposta por execução. A pontuação recebida também fica registrada.
CREATE TABLE resposta_atividade (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 execucao_id INT NOT NULL, questao_id INT NOT NULL, alternativa_id INT NOT NULL,
 pontuacao_obtida NUMERIC(7,2) NOT NULL CHECK(pontuacao_obtida>=0),
 tempo_gasto_seg INT CHECK(tempo_gasto_seg>=0),
 data_resposta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(execucao_id,questao_id),
 FOREIGN KEY(execucao_id,questao_id) REFERENCES execucao_questao(execucao_id,questao_id),
 FOREIGN KEY(alternativa_id,questao_id) REFERENCES atividade_alternativa(id,questao_id)
);

-- Depois de terminar a tarefa, o usuário avalia se ela foi útil para desenvolver a habilidade.
-- A escala Likert vai de 1 Discordo totalmente a 5 Concordo totalmente.
-- Ele também pode deixar um comentário, se quiser. É um feedback por execução, separado dos pontos das respostas.
CREATE TABLE feedback_atividade (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 execucao_id INT NOT NULL UNIQUE REFERENCES execucao(id),
 avaliacao_likert SMALLINT NOT NULL CHECK(avaliacao_likert BETWEEN 1 AND 5),
 comentario TEXT,
 data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON COLUMN feedback_atividade.avaliacao_likert IS
 'Avalia a afirmação Esta tarefa foi útil para desenvolver esta habilidade. 1 Discordo totalmente; 2 Discordo; 3 Nem concordo nem discordo; 4 Concordo; 5 Concordo totalmente.';

