-- Quando a pessoa muda o perfil, guardamos como ele era ANTES da mudança.
-- Exemplo: se o tempo passa de 'curto' para 'longo', o histórico recebe 'curto'.
-- O novo valor continua em perfil_usuario. Não gera histórico no primeiro cadastro.
CREATE OR REPLACE FUNCTION capacitacao.guardar_perfil_anterior()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    INSERT INTO capacitacao.historico_perfil (
        usuario_id, ambiente, tempo, recursos, interlocutores,
        origem, motivo, data_registro
    ) VALUES (
        OLD.usuario_id, OLD.ambiente, OLD.tempo, OLD.recursos, OLD.interlocutores,
        OLD.origem_atualizacao, 'Perfil anterior à alteração', CURRENT_TIMESTAMP
    );

    NEW.atualizado_em := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- Só dispara se algum dado do contexto realmente mudou.
-- Salvar os mesmos valores ou mudar apenas a data não cria cópias no histórico.
CREATE TRIGGER trg_historico_perfil
BEFORE UPDATE ON capacitacao.perfil_usuario
FOR EACH ROW
WHEN (
    ROW(OLD.ambiente, OLD.tempo, OLD.recursos, OLD.interlocutores)
    IS DISTINCT FROM
    ROW(NEW.ambiente, NEW.tempo, NEW.recursos, NEW.interlocutores)
)
EXECUTE FUNCTION capacitacao.guardar_perfil_anterior();

